"""LLM conversation orchestration with retrieval-augmented project evidence.

Every answer is generated by the configured language model.  The module never
selects a canned response: if the provider is missing or fails, it raises an
error that the UI can explain honestly.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from typing import Any, Iterable, Iterator

from src.assistant import llm
from src.assistant.config import (
    LLMConfig,
    LLMConfigurationError,
    configuration_help,
    load_config,
    require_config,
)
from src.assistant.corpus import default_retrieval_index
from src.assistant.rag import Evidence, collect_sources, format_context, retrieve

MAX_HISTORY_MESSAGES = 12
MAX_HISTORY_CHARS = 3500

SYSTEM_PROMPT = f"""You are the AI RESILIENCE Disaster Intelligence Assistant, a conversational
assistant focused on disaster management for Kochi, Ernakulam, Kerala, and India.
You can also answer general-knowledge and everyday questions naturally.

## Your expertise
Floods and urban waterlogging; landslides and slope failure; cyclones, storms,
heatwaves and lightning; earthquakes; industrial and chemical incidents; air
pollution and public-health impacts; hospital and health-system vulnerability;
disaster probability and risk assessment; smart mitigation design; mitigation
budgeting and prioritisation; and household, community and institutional
preparedness.

## How to answer
- Generate the answer yourself in clear, natural language. Do not copy a fixed
  template and do not claim to have retrieved an answer that is not present.
- Match the user's level: explain simply when asked, give technical detail when
  the user is technical. Use short headings and bullet points for complex answers.
- Explain causes, consequences, trade-offs, and practical solutions. Distinguish
  what is known, what is uncertain, and what should be checked locally.
- You may answer general questions from your own knowledge. Project-specific
  claims must be grounded in the retrieved evidence supplied below.
- When you use retrieved project evidence, cite it inline like
  `(Source: Publisher)` and finish with a short **Sources** list containing the
  URLs that were actually used. Never invent a citation, URL, statistic, date,
  probability, casualty figure, or forecast.
- The project data may be historical, incomplete, or unvalidated. Describe it as
  such. Never present a historical reading as a live condition.
- If the retrieved evidence does not answer the question, say what the project
  does and does not contain, then give general guidance clearly labelled as
  general guidance.

## Safety rules
- If the user describes an active emergency (trapped people, rising water, fire,
  collapse, gas leak, serious injury, or immediate danger), begin by telling them
  to contact official emergency services now: **112** (national emergency
  response), **108** (ambulance), and **101** (fire and rescue). Tell them to
  follow current instructions from KSDMA, IMD, and the district administration.
- Never claim to dispatch help, confirm a rescue, issue an official warning, or
  know real-time conditions. Never tell someone to delay emergency action.
- Do not invent a local flood probability, AQI value, rainfall total, water
  level, or evacuation order. The project has no live monitoring feed.
- Do not identify a specific factory as the cause of air pollution. The project
  has no verified facility coordinates or measured stack emissions for attribution.
- For medical, structural, or legal decisions, recommend a qualified local
  professional or official authority.

## Style
Be warm, direct, and useful. Avoid boilerplate disclaimers repeated in every
paragraph; one clear safety note is enough. Do not mention retrieval scores or
internal record IDs. If the user asks what this application can do, describe the
AI RESILIENCE modules and this assistant honestly.

Today's date is {date.today().isoformat()}.
"""


@dataclass
class ReplyPlan:
    """A prepared LLM call plus the evidence that grounds it."""

    question: str
    messages: list[dict[str, str]]
    evidence: list[Evidence]
    sources: list[dict[str, str]]
    config: LLMConfig

    def stream(self) -> Iterator[str]:
        return llm.stream_chat(self.messages, self.config)

    @property
    def provider(self) -> str:
        return self.config.provider

    @property
    def model(self) -> str:
        return self.config.model


def _coerce_history(history: Iterable[dict[str, Any]] | None) -> list[dict[str, str]]:
    """Normalize supported history shapes into chat messages."""
    messages: list[dict[str, str]] = []
    for item in history or []:
        if not isinstance(item, dict):
            continue
        role = str(item.get("role", "")).strip().lower()
        content = str(item.get("content", "")).strip()
        if role not in {"user", "assistant"}:
            question = str(item.get("question", "")).strip()
            answer = str(item.get("answer", "")).strip()
            if question:
                messages.append({"role": "user", "content": question[:MAX_HISTORY_CHARS]})
            if answer:
                messages.append({"role": "assistant", "content": answer[:MAX_HISTORY_CHARS]})
            continue
        if content:
            messages.append({"role": role, "content": content[:MAX_HISTORY_CHARS]})
    return messages[-MAX_HISTORY_MESSAGES:]


def build_messages(
    question: str,
    history: Iterable[dict[str, Any]] | None,
    evidence: Iterable[Evidence],
) -> list[dict[str, str]]:
    """Build the provider message list with system, RAG context and history."""
    messages: list[dict[str, str]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    context = format_context(evidence)
    if context:
        messages.append(
            {
                "role": "system",
                "content": (
                    "## Retrieved project evidence\n"
                    "The following records come from this project's reviewed knowledge and "
                    "dated module summaries. Use them only where relevant. They are not live "
                    "observations. If a record is unrelated to the question, ignore it.\n\n"
                    f"{context}"
                ),
            }
        )
    messages.extend(_coerce_history(history))
    messages.append({"role": "user", "content": question})
    return messages


def prepare_reply(
    question: str,
    history: Iterable[dict[str, Any]] | None = None,
    *,
    config: LLMConfig | None = None,
) -> ReplyPlan:
    """Retrieve project evidence and prepare a streaming LLM response.

    Raises ``LLMConfigurationError`` when no usable provider is configured.
    """
    text = str(question or "").strip()
    if not text:
        raise ValueError("Enter a question before sending.")
    resolved = config or require_config()
    evidence = retrieve(text, history)
    sources = collect_sources(evidence)
    return ReplyPlan(
        question=text,
        messages=build_messages(text, history, evidence),
        evidence=evidence,
        sources=sources,
        config=resolved,
    )


def chat_once(
    question: str,
    history: Iterable[dict[str, Any]] | None = None,
    *,
    config: LLMConfig | None = None,
) -> dict[str, Any]:
    """Return a complete answer.  Used by tests, scripts and non-streaming callers."""
    plan = prepare_reply(question, history, config=config)
    answer = "".join(plan.stream())
    return {
        "answer": answer,
        "sources": plan.sources,
        "evidence": [item.as_dict() for item in plan.evidence],
        "provider": plan.provider,
        "model": plan.model,
    }


def assistant_status() -> dict[str, Any]:
    """Expose safe configuration and index metadata for the UI."""
    try:
        config = load_config()
        config_error = None
    except LLMConfigurationError as exc:
        config = None
        config_error = str(exc)

    knowledge_topics = 0
    retrieval_chunks = 0
    try:
        from src.assistant.knowledge import load_knowledge

        knowledge_topics = len(load_knowledge())
        retrieval_chunks = len(default_retrieval_index().chunks)
    except Exception:
        pass

    status: dict[str, Any] = {
        "configured": bool(config and config.configured),
        "provider": config.provider if config else None,
        "model": config.model if config else None,
        "base_url": config.base_url if config else None,
        "knowledge_topics": knowledge_topics,
        "retrieval_chunks": retrieval_chunks,
        "error": config_error,
        "help": configuration_help(),
    }
    if config and config.configured:
        status["message"] = f"Connected provider: {config.provider} · model: {config.model}"
    elif config:
        status["message"] = (
            f"Provider {config.provider} is selected but no API key is configured."
        )
    else:
        status["message"] = config_error or "The language model is not configured."
    return status


